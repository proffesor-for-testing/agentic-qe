/**
 * #1049 review round 4: workspace members are found by real glob expansion
 * (`**`, multi-segment, negations), stay inside the project root, and every
 * planning problem (malformed lockfile, unreadable member, unexpandable
 * pattern) makes the scan not complete. The lockfile walk-up never leaves
 * AQE_PROJECT_ROOT. Local OSV stub; no real network.
 */
import { describe, it, expect, beforeAll, afterAll, afterEach, vi } from 'vitest';
import { createServer, type Server } from 'node:http';
import type { AddressInfo } from 'node:net';
import { mkdirSync, mkdtempSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { DependencyScanner } from '../../../../../src/domains/security-compliance/services/scanners/dependency-scanner';
import { pnpmWorkspacePatterns, workspaceGlobToRegExp } from '../../../../../src/domains/security-compliance/services/scanners/workspace-members';
import { OSVClient } from '../../../../../src/shared/security/osv-client';
import type { MemoryBackend } from '../../../../../src/kernel/interfaces';
import type { SecurityScannerConfig, DependencyScanResult } from '../../../../../src/domains/security-compliance/services/scanners/scanner-types';

let server: Server;
let baseUrl: string;
let queried: string[];
const dirs: string[] = [];
const savedRoot = process.env.AQE_PROJECT_ROOT;

beforeAll(async () => {
  server = createServer((req, res) => {
    let body = '';
    req.on('data', (c) => { body += c; });
    req.on('end', () => {
      res.writeHead(200, { 'Content-Type': 'application/json' });
      const queries = (JSON.parse(body || '{"queries":[]}') as { queries: Array<{ package: { name: string }; version: string }> }).queries;
      queried.push(...queries.map((q) => `${q.package.name}@${q.version}`));
      res.end(JSON.stringify({ results: queries.map(() => ({})) }));
    });
  });
  await new Promise<void>((r) => server.listen(0, '127.0.0.1', r));
  baseUrl = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
});

afterAll(async () => {
  server.closeAllConnections?.();
  await new Promise<void>((r) => server.close(() => r()));
  for (const d of dirs) rmSync(d, { recursive: true, force: true });
});

afterEach(() => {
  if (savedRoot === undefined) delete process.env.AQE_PROJECT_ROOT; else process.env.AQE_PROJECT_ROOT = savedRoot;
});

const config: SecurityScannerConfig = {
  defaultRuleSets: [], maxConcurrentScans: 1, timeout: 10000, enableFalsePositiveDetection: false,
  dastMaxDepth: 1, dastActiveScanning: false, enableLLMAnalysis: false, llmModelTier: 1, enableSemgrep: false,
};

function tree(base: string, files: Record<string, string | object>): void {
  for (const [name, content] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(base, name)), { recursive: true });
    writeFileSync(path.join(base, name), typeof content === 'string' ? content : JSON.stringify(content));
  }
}

/** A temp project (git repo) with the given files; returns its root. */
function repo(files: Record<string, string | object>, git = true): string {
  const dir = mkdtempSync(path.join(tmpdir(), 'aqe-1049-ws-'));
  dirs.push(dir);
  if (git) mkdirSync(path.join(dir, '.git'));
  tree(dir, files);
  return dir;
}

async function scan(root: string, manifest = path.join(root, 'package.json')): Promise<DependencyScanResult> {
  queried = [];
  process.env.AQE_PROJECT_ROOT = root;
  const memory = { set: vi.fn(), get: vi.fn(), search: vi.fn().mockResolvedValue([]) } as unknown as MemoryBackend;
  const scanner = new DependencyScanner(config, memory, undefined, new OSVClient({ baseUrl, retries: 0, enableCache: false }));
  const result = await scanner.scanPackageJson(manifest);
  expect(result.success).toBe(true);
  return (result as { value: DependencyScanResult }).value;
}

const YARN_HEADER = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n';

describe('B1: workspace globs are really expanded', () => {
  it('yarn 1, workspaces ["apps/**"]: a nested member (apps/web/ui) is scanned; node_modules is skipped', async () => {
    const root = repo({
      'package.json': { name: 'root', private: true, workspaces: ['apps/**'] },
      'apps/web/ui/package.json': { name: '@y/ui', version: '1.0.0', dependencies: { minimist: '1.2.5' } },
      'apps/web/node_modules/dep/package.json': { name: 'dep', version: '1.0.0', dependencies: { evil: '1.0.0' } },
      'yarn.lock': `${YARN_HEADER}minimist@1.2.5:\n  version "1.2.5"\n  resolved "https://registry.yarnpkg.com/minimist/-/minimist-1.2.5.tgz"\n`,
    });
    const value = await scan(root);
    expect(value.workspaceMembers).toEqual(['apps/web/ui']);
    expect(queried).toEqual(['minimist@1.2.5']);
    expect(value).toMatchObject({ status: 'complete', lockfile: 'yarn.lock' });
  });

  it('no lockfile, workspaces ["packages/*/*"]: packages/group/ui is scanned', async () => {
    const root = repo({
      'package.json': { name: 'root', private: true, workspaces: ['packages/*/*'] },
      'packages/group/ui/package.json': { name: '@g/ui', dependencies: { minimist: '1.2.5' } },
    });
    const value = await scan(root);
    expect(value.workspaceMembers).toEqual(['packages/group/ui']);
    expect(queried).toEqual(['minimist@1.2.5']);
  });

  it('negation is honoured for npm/yarn workspaces and pnpm-workspace.yaml', async () => {
    const npm = repo({
      'package.json': { name: 'root', workspaces: ['packages/*', '!packages/x'] },
      'packages/a/package.json': { name: 'a', dependencies: { minimist: '1.2.5' } },
      'packages/x/package.json': { name: 'x', dependencies: { qs: '6.7.0' } },
    });
    const value = await scan(npm);
    expect(value.workspaceMembers).toEqual(['packages/a']);
    expect(queried).toEqual(['minimist@1.2.5']);

    const pnpm = repo({
      'package.json': { name: 'root' },
      'pnpm-workspace.yaml': "packages:\n  - 'packages/*'\n  - '!packages/x'\nonlyBuiltDependencies:\n  - esbuild\n",
      'packages/a/package.json': { name: 'a', dependencies: { minimist: '1.2.5' } },
      'packages/x/package.json': { name: 'x', dependencies: { qs: '6.7.0' } },
      'esbuild/package.json': { name: 'not-a-member', dependencies: { qs: '6.7.0' } },
    });
    const pv = await scan(pnpm);
    expect(pv.workspaceMembers).toEqual(['packages/a']);
    expect(queried).toEqual(['minimist@1.2.5']);
  });

  it('pnpm-workspace.yaml: only items under packages: are patterns', () => {
    expect(pnpmWorkspacePatterns("packages:\n  - 'packages/*'\n  - apps/**  # comment\n\nonlyBuiltDependencies:\n  - esbuild\ncatalog:\n  x: 1\n"))
      .toEqual({ patterns: ['packages/*', 'apps/**'] });
    expect(pnpmWorkspacePatterns('onlyBuiltDependencies:\n  - esbuild\n')).toEqual({ patterns: [] });
    expect(pnpmWorkspacePatterns("packages: ['a/*', \"b\"]\n")).toEqual({ patterns: ['a/*', 'b'] });
  });

  it('round 5: every valid YAML form of packages: is read (non-indented, inline + comment, multi-line flow, BOM)', () => {
    expect(pnpmWorkspacePatterns("packages:\n- 'packages/*'\n- apps/**\nonlyBuiltDependencies:\n- esbuild\n")).toEqual({ patterns: ['packages/*', 'apps/**'] });
    expect(pnpmWorkspacePatterns("packages: ['packages/*'] # members\n")).toEqual({ patterns: ['packages/*'] });
    expect(pnpmWorkspacePatterns("packages: [\n  'packages/*',\n  \"apps/*\"  # c\n]\n")).toEqual({ patterns: ['packages/*', 'apps/*'] });
    expect(pnpmWorkspacePatterns("﻿packages:\n  - 'packages/*'\n")).toEqual({ patterns: ['packages/*'] });
    expect(pnpmWorkspacePatterns('')).toEqual({ patterns: [] });
  });

  it('round 5: workspace globs match symlink paths like the glob engine (*, **, ?, braces)', () => {
    expect(workspaceGlobToRegExp('packages/*').test('packages/real')).toBe(true);
    expect(workspaceGlobToRegExp('packages/*').test('packages/a/b')).toBe(false);
    expect(workspaceGlobToRegExp('apps/**').test('apps/web/ui')).toBe(true);
    expect(workspaceGlobToRegExp('**/ui').test('ui')).toBe(true);
    expect(workspaceGlobToRegExp('**/ui').test('apps/web/ui')).toBe(true);
    expect(workspaceGlobToRegExp('{apps,libs}/*').test('libs/x')).toBe(true);
    expect(workspaceGlobToRegExp('pkg-?').test('pkg-a')).toBe(true);
    expect(workspaceGlobToRegExp('a.b/*').test('aXb/c')).toBe(false);
  });

  it('round 5: an unparsable file or a non-list packages is an error, never []', () => {
    expect(pnpmWorkspacePatterns("packages: ['a/*'\n")).toEqual({ error: expect.stringMatching(/could not be parsed/) });
    expect(pnpmWorkspacePatterns('packages: packages/*\n')).toEqual({ error: expect.stringMatching(/not a list of strings/) });
    expect(pnpmWorkspacePatterns('packages:\n  - 1\n')).toEqual({ error: expect.stringMatching(/not a list of strings/) });
    expect(pnpmWorkspacePatterns('- a\n- b\n')).toEqual({ error: expect.stringMatching(/not a YAML mapping/) });
  });
});

describe('round 5: pnpm-workspace.yaml forms end to end, symlinks, root, notes, BOM', () => {
  const member = { 'packages/web/package.json': { name: '@m/web', dependencies: { minimist: '1.2.5' } } };

  it.each([
    ['non-indented sequence', "packages:\n- 'packages/*'\n"],
    ['inline array + comment', "packages: ['packages/*'] # members\n"],
    ['multi-line flow array', "packages: [\n  'packages/*',\n]\n"],
  ])('no lockfile, %s: the member is scanned', async (_name, yaml) => {
    const root = repo({ 'package.json': { name: 'mono', private: true }, 'pnpm-workspace.yaml': yaml, ...member });
    const value = await scan(root);
    expect(value.workspaceMembers).toEqual(['packages/web']);
    expect(queried).toEqual(['minimist@1.2.5']);
    expect(value.status).toBe('complete');
  });

  it('an unparsable pnpm-workspace.yaml makes the scan incomplete (fail-closed)', async () => {
    const root = repo({ 'package.json': { name: 'mono', dependencies: { minimist: '1.2.5' } }, 'pnpm-workspace.yaml': "packages: ['packages/*'\n", ...member });
    const value = await scan(root);
    expect(value.status).toBe('incomplete');
    expect(value.resolutionErrors).toEqual([expect.stringMatching(/pnpm-workspace\.yaml could not be parsed/)]);
  });

  it('a symlinked member directory inside the root is a member; "**" never makes the root a member', async () => {
    const root = repo({
      'package.json': { name: 'mono', workspaces: ['**'] },
      'libs/real/package.json': { name: 'real', dependencies: { minimist: '1.2.5' } },
    });
    mkdirSync(path.join(root, 'packages'));
    symlinkSync(path.join(root, 'libs', 'real'), path.join(root, 'packages', 'real'), 'dir');
    const value = await scan(root);
    expect(value.workspaceMembers).not.toContain('.');
    expect(value.workspaceMembers).toContain('libs/real');

    const linkOnly = repo({
      'package.json': { name: 'mono', workspaces: ['packages/*'] },
      'libs/real/package.json': { name: 'real', dependencies: { minimist: '1.2.5' } },
    });
    mkdirSync(path.join(linkOnly, 'packages'));
    symlinkSync(path.join(linkOnly, 'libs', 'real'), path.join(linkOnly, 'packages', 'real'), 'dir');
    const lv = await scan(linkOnly);
    expect(lv.workspaceMembers).toEqual(['packages/real']);
    expect(queried).toEqual(['minimist@1.2.5']);
  });

  it('a member package.json symlinked to a file outside the root is excluded and reported', async () => {
    const outside = repo({ 'package.json': { name: 'outside', dependencies: { qs: '6.7.0' } } }, false);
    const root = repo({ 'package.json': { name: 'mono', workspaces: ['packages/*'] } });
    mkdirSync(path.join(root, 'packages', 'x'), { recursive: true });
    symlinkSync(path.join(outside, 'package.json'), path.join(root, 'packages', 'x', 'package.json'));
    const value = await scan(root);
    expect(value.workspaceMembers).toEqual([]);
    expect(value.excludedMembers).toEqual([expect.objectContaining({ path: 'packages/x', reason: expect.stringMatching(/package\.json resolves outside/) })]);
    expect(queried).toEqual([]);
  });

  it('a pattern naming a file is a note (not an error); an unmatched plain glob is a note too', async () => {
    const root = repo({
      'package.json': { name: 'mono', workspaces: ['packages/a/package.json', 'nothing/*'] },
      'packages/a/package.json': { name: 'a' },
    });
    const value = await scan(root);
    expect(value.status).toBe('complete');
    expect(value.workspaceWarnings).toEqual([
      expect.stringMatching(/"packages\/a\/package\.json" matches file\(s\), not package directories/),
      expect.stringMatching(/"nothing\/\*" matches no package directory/),
    ]);
  });

  it('a pnpm-lock.yaml with a leading BOM is read, not flagged malformed', async () => {
    const root = repo({
      'package.json': { dependencies: { minimist: '^1.2.0' } },
      'pnpm-lock.yaml': "﻿lockfileVersion: '9.0'\n\nimporters:\n\n  .:\n    dependencies:\n      minimist:\n        specifier: ^1.2.0\n        version: 1.2.5\n",
    });
    const value = await scan(root);
    expect(value).toMatchObject({ status: 'complete', lockfile: 'pnpm-lock.yaml', resolutionErrors: [] });
    expect(queried).toEqual(['minimist@1.2.5']);
  });
});

describe('B2: planning errors make the scan not complete', () => {
  it('a malformed member package.json: incomplete, the error is reported, other members still checked', async () => {
    const root = repo({
      'package.json': { name: 'root', workspaces: ['packages/a', 'packages/b'] },
      'packages/a/package.json': '{ "name": "a", "dependencies": { "lodash": "4.17.11" ',
      'packages/b/package.json': { name: 'b', dependencies: { minimist: '1.2.5' } },
    });
    const value = await scan(root);
    expect(value).toMatchObject({ status: 'incomplete', measured: false, workspaceMembers: ['packages/b'] });
    expect(value.resolutionErrors).toEqual([expect.stringMatching(/packages\/a\/package\.json could not be read or parsed/)]);
    expect(value.error).toMatch(/packages\/a\/package\.json/);
    expect(queried).toEqual(['minimist@1.2.5']);
  });

  it.each([
    ['package-lock.json', '{ "lockfileVersion": 3, "packages": '],
    ['package-lock.json', '[]'],
    ['pnpm-lock.yaml', 'this is not a lockfile\n'],
    ['yarn.lock', 'garbage\n'],
  ])('a malformed %s is an error, not "no lockfile"', async (file, content) => {
    const root = repo({ 'package.json': { dependencies: { minimist: '1.2.5' } }, [file]: content });
    const value = await scan(root);
    expect(value.status).not.toBe('complete');
    expect(value.measured).toBe(false);
    expect(value.resolutionErrors).toEqual([expect.stringMatching(new RegExp(`${file.replace('.', '\\.')} could not be read or parsed`))]);
  });
});

describe('containment and walk-up bounds', () => {
  it('a "../" workspace pattern and a symlinked member outside the root are excluded, never sent to OSV', async () => {
    const outside = repo({ 'package.json': { name: 'outside', dependencies: { qs: '6.7.0' } } }, false);
    const root = repo({
      'package.json': { name: 'root', workspaces: ['packages/*', `packages/../../${path.basename(outside)}`, 'linked'] },
      'packages/a/package.json': { name: 'a', dependencies: { minimist: '1.2.5' } },
    });
    symlinkSync(outside, path.join(root, 'linked'), 'dir');
    const value = await scan(root);
    expect(value.workspaceMembers).toEqual(['packages/a']);
    expect(queried).toEqual(['minimist@1.2.5']);
    expect(value.excludedMembers!.map((e) => e.path).sort()).toEqual(['linked', `packages/../../${path.basename(outside)}`].sort());
    expect(value.excludedMembers![0].reason).toMatch(/outside the project root/);
  });

  it('the lockfile walk-up stops at AQE_PROJECT_ROOT even without .git', async () => {
    // The parent's lockfile does cover proj (as a workspace member), so only the bound keeps it out.
    const parent = repo({ 'package-lock.json': { lockfileVersion: 3, packages: {
      '': { workspaces: ['proj'] }, proj: { dependencies: { lodash: '^4.17.0' } }, 'node_modules/lodash': { version: '4.17.11' },
    } } }, false);
    tree(parent, { 'proj/package.json': { dependencies: { lodash: '^4.17.0' } } });
    const value = await scan(path.join(parent, 'proj'));
    expect(value.lockfile).toBeNull();
    expect(value.uncheckedPackages).toEqual([expect.objectContaining({ name: 'lodash', reason: 'version range "^4.17.0", no lockfile resolution' })]);
    expect(queried).toEqual([]);
  });
});
